def test_pruning_keeps_the_newest_two_snapshots(tmp_path: Path) -> None:
    """Otherwise every guided install leaves another copy of the plugin on flash.

    The newest is the way back from the install that has just succeeded, and the one
    before it is the way back from the install before that. Older ones have been
    superseded twice and nobody is going to reach for them.
    """
    backups = tmp_path / "mqttbridge-backups"
    backups.mkdir()
    for index, nonce in enumerate(
        ("aaaaaaaaaaaa", "bbbbbbbbbbbb", "cccccccccccc", "dddddddddddd")
    ):
        directory = backups / f"ha-installer-{nonce}"
        directory.mkdir()
        (directory / "snapshot.json").write_text("{}", encoding="utf-8")
        os.utime(directory, (1_700_000_000 + index, 1_700_000_000 + index))

    removed = prune_snapshots(backups)

    assert removed == ["ha-installer-aaaaaaaaaaaa", "ha-installer-bbbbbbbbbbbb"]
    assert sorted(child.name for child in backups.iterdir()) == [
        "ha-installer-cccccccccccc",
        "ha-installer-dddddddddddd",
    ]


def test_pruning_never_removes_the_snapshot_of_the_install_that_is_committing(
    tmp_path: Path,
) -> None:
    """A timestamp on these receivers is not a clock.

    Many have no battery-backed one: they boot in 1970 and jump to the real time when
    NTP answers, which can be minutes into an install and so after its snapshot was
    taken. Ordering by modification time would then rank the snapshot that is the only
    way back from the committing install as the oldest, and delete it.
    """
    backups = tmp_path / "mqttbridge-backups"
    backups.mkdir()
    for nonce, modified in (
        ("aaaaaaaaaaaa", 1_700_000_100),
        ("bbbbbbbbbbbb", 1_700_000_200),
        # Taken last, stamped before the receiver's clock was corrected.
        ("cccccccccccc", 1_000_000_000),
    ):
        directory = backups / f"ha-installer-{nonce}"
        directory.mkdir()
        os.utime(directory, (modified, modified))

    removed = prune_snapshots(backups, keep_name="ha-installer-cccccccccccc")

    assert removed == ["ha-installer-aaaaaaaaaaaa"]
    assert sorted(child.name for child in backups.iterdir()) == [
        "ha-installer-bbbbbbbbbbbb",
        "ha-installer-cccccccccccc",
    ]


def test_pruning_after_a_failed_install_still_leaves_exactly_two(tmp_path: Path) -> None:
    """A failed run's snapshot is an ordinary candidate, not a third thing kept.

    Pruning only runs once a transaction has committed, so a run that rolls back leaves
    its snapshot behind — as it should, it is the evidence — and the directory is one
    fuller than the rule allows until the next install succeeds. Observed on a receiver
    after the rollback drill of 2026-09-22: two snapshots from earlier successes and one
    from the failed run. The next success has to bring that back to two.
    """
    backups = tmp_path / "mqttbridge-backups"
    backups.mkdir()
    for nonce, modified in (
        ("aaaaaaaaaaaa", 1_700_000_100),
        ("bbbbbbbbbbbb", 1_700_000_200),
        # The run that rolled back.
        ("cccccccccccc", 1_700_000_300),
        # The install that is committing now.
        ("dddddddddddd", 1_700_000_400),
    ):
        directory = backups / f"ha-installer-{nonce}"
        directory.mkdir()
        os.utime(directory, (modified, modified))

    removed = prune_snapshots(backups, keep_name="ha-installer-dddddddddddd")

    assert removed == ["ha-installer-aaaaaaaaaaaa", "ha-installer-bbbbbbbbbbbb"]
    assert sorted(child.name for child in backups.iterdir()) == [
        "ha-installer-cccccccccccc",
        "ha-installer-dddddddddddd",
    ]


def test_pruning_touches_nothing_it_did_not_make(tmp_path: Path) -> None:
    """`rmtree` down a symlink would leave the backups directory altogether."""
    backups = tmp_path / "mqttbridge-backups"
    backups.mkdir()
    outside = tmp_path / "somebody-elses-data"
    outside.mkdir()
    (outside / "keep").write_text("keep\n", encoding="utf-8")
    (backups / "ha-installer-000000000000").symlink_to(outside, target_is_directory=True)
    (backups / "manual-backup-before-the-update").mkdir()
    (backups / ".ha-installer.lock").mkdir()
    (backups / "ha-installer-111111111111.tar").write_text("an archive\n", encoding="utf-8")
    superseded = backups / "ha-installer-333333333333"
    superseded.mkdir()
    os.utime(superseded, (1_700_000_000, 1_700_000_000))
    (backups / "ha-installer-222222222222").mkdir()

    assert prune_snapshots(backups, keep=1) == ["ha-installer-333333333333"]

    assert (outside / "keep").is_file()
    assert sorted(child.name for child in backups.iterdir()) == [
        ".ha-installer.lock",
        "ha-installer-000000000000",
        "ha-installer-111111111111.tar",
        "ha-installer-222222222222",
        "manual-backup-before-the-update",
    ]


