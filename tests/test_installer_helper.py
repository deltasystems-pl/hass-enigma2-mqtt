def _write(root: Path, relative: str, value: str) -> Path:
    target = root / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(value, encoding="utf-8")
    return target


def _receiver_tree(root: Path) -> None:
    _write(
        root,
        "usr/lib/opkg/status",
        f"Package: unrelated\nVersion: 7\n\nPackage: {PACKAGE}\nVersion: 0.0.9\nDescription: old\n",
    )
    _write(root, f"usr/lib/opkg/info/{PACKAGE}.list", "/old/plugin.py\n")
    _write(root, "usr/lib/opkg/info/unrelated.list", "/keep\n")
    _write(
        root,
        "usr/lib/enigma2/python/Plugins/Extensions/MQTTBridge/plugin.py",
        "old plugin\n",
    )
    _write(
        root,
        "usr/lib/enigma2/python/Plugins/Extensions/WebInterface/WebChilds/External/MQTTBridge.py",
        "old shim\n",
    )
    _write(
        root,
        "usr/lib/enigma2/python/Plugins/Extensions/WebInterface/"
        "WebChilds/External/__pycache__/MQTTBridge.cpython-312.pyc",
        "old bytecode\n",
    )
    _write(
        root,
        "etc/enigma2/settings",
        "config.misc.keep=true\n"
        "config.plugins.mqttbridge.host=old-broker\n"
        "config.plugins.mqttbridge.port=1883\n",
    )
    _write(root, "etc/enigma2/mqttbridge.json", '{"old":true}\n')


def _move_opkg_database(root: Path, base: str) -> None:
    """Move the database where an image's own opkg.conf says it is.

    OpenViX 6.6: `/usr/lib/opkg` exists and holds `alternatives/` and nothing else,
    while `/etc/opkg/opkg.conf` names `/var/lib/opkg`. The empty directory is part of
    the fixture, because it is what made the hard-coded path look plausible.
    """
    legacy = root / "usr/lib/opkg"
    target = root / base
    target.parent.mkdir(parents=True, exist_ok=True)
    legacy.rename(target)
    (legacy / "alternatives").mkdir(parents=True)


def _write_opkg_conf(root: Path, base: str) -> None:
    _write(
        root,
        "etc/opkg/opkg.conf",
        "# generated by the image\n"
        "src/gz all http://feeds.example.invalid/all\n"
        "dest root /\n"
        f"option lists_dir /{base}/lists\n"
        f"option info_dir /{base}/info\n"
        f"option status_file /{base}/status\n",
    )
    # Architectures live in their own file on this image, and say nothing about paths.
    _write(root, "etc/opkg/arch.conf", "arch all 1\narch mips32el 10\n")


def test_the_database_is_found_where_the_image_says_it_is(tmp_path: Path) -> None:
    """The layout the guided installer died on, snapshotted and rolled back."""
    root = tmp_path / "root"
    backup = tmp_path / "backup"
    _receiver_tree(root)
    _move_opkg_database(root, "var/lib/opkg")
    _write_opkg_conf(root, "var/lib/opkg")

    metadata = snapshot(root, backup)

    assert metadata["package_status"] is True
    assert metadata["opkg_info"] is True

    _write(
        root,
        "var/lib/opkg/status",
        f"Package: unrelated\nVersion: 8\n\nPackage: {PACKAGE}\nVersion: 0.1.0\n",
    )
    _write(root, f"var/lib/opkg/info/{PACKAGE}.list", "/new/plugin.py\n")

    restore(root, backup, restore_provisioning=True, restore_settings=True)

    status = (root / "var/lib/opkg/status").read_text(encoding="utf-8")
    assert f"Package: {PACKAGE}\nVersion: 0.0.9" in status
    assert "Package: unrelated\nVersion: 8" in status
    assert (root / f"var/lib/opkg/info/{PACKAGE}.list").read_text() == "/old/plugin.py\n"
    # The empty directory that used to be mistaken for the database is untouched.
    assert list((root / "usr/lib/opkg").iterdir()) == [root / "usr/lib/opkg/alternatives"]


